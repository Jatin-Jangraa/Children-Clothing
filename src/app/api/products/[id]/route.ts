import { NextRequest, NextResponse } from "next/server";
import { revalidatePath } from "next/cache";
import { connectDB } from "@/lib/db";
import Product from "@/models/Product";
import { auth } from "@/lib/auth";

export async function GET(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    await connectDB();
    const { id } = await params;
    const product = await Product.findById(id).populate("category").lean();
    if (!product) return NextResponse.json({ success: false, error: "Not found" }, { status: 404 });
    return NextResponse.json({ success: true, data: product });
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error.message }, { status: 500 });
  }
}

export async function PUT(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    const session = await auth();
    if (!session || session.user.role !== "admin") {
      return NextResponse.json({ success: false, error: "Unauthorized" }, { status: 401 });
    }
    await connectDB();
    const { id } = await params;
    const body = await req.json();

    // Prevent modifying immutable or autogenerated fields
    delete body._id;
    delete body.__v;
    delete body.createdAt;
    delete body.updatedAt;

    // Handle populated category object
    if (body.category && typeof body.category === "object" && body.category._id) {
      body.category = body.category._id;
    }

    // Format age groups
    if (body.ageGroups && Array.isArray(body.ageGroups) && body.ageGroups.length > 0) {
      if (!body.ageGroup) body.ageGroup = body.ageGroups.join(", ");
    } else if (body.ageGroup && (!body.ageGroups || body.ageGroups.length === 0)) {
      body.ageGroups = [body.ageGroup];
    }

    // Update slug if name is provided or updated
    if (body.name && (!body.slug || body.slug.trim() === "")) {
      body.slug = body.name
        .toLowerCase()
        .replace(/[^\w\s-]/g, "")
        .replace(/[\s_-]+/g, "-")
        .replace(/^-+|-+$/g, "");
    }

    // Automatically recalculate discount if price and mrp are provided
    if (body.price !== undefined && body.mrp !== undefined && body.mrp > 0) {
      if (body.discount === undefined || body.discount === null) {
        body.discount = Math.round(((body.mrp - body.price) / body.mrp) * 100);
      }
    }

    const product = await Product.findByIdAndUpdate(id, body, { new: true, runValidators: true });
    if (!product) return NextResponse.json({ success: false, error: "Not found" }, { status: 404 });

    // Invalidate Next.js cache so changes immediately reflect on the website
    try {
      revalidatePath("/");
      revalidatePath("/shop");
      revalidatePath("/admin/products");
      if (product.slug) {
        revalidatePath(`/product/${product.slug}`);
      }
    } catch (e) {
      console.warn("Revalidation notice:", e);
    }

    return NextResponse.json({ success: true, data: product });
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error.message }, { status: 500 });
  }
}

export async function DELETE(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    const session = await auth();
    if (!session || session.user.role !== "admin") {
      return NextResponse.json({ success: false, error: "Unauthorized" }, { status: 401 });
    }
    await connectDB();
    const { id } = await params;
    const deleted = await Product.findByIdAndDelete(id);
    if (!deleted) return NextResponse.json({ success: false, error: "Not found" }, { status: 404 });

    try {
      revalidatePath("/");
      revalidatePath("/shop");
      revalidatePath("/admin/products");
    } catch {}

    return NextResponse.json({ success: true, message: "Deleted" });
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error.message }, { status: 500 });
  }
}
